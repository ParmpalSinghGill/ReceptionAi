"""Alembic environment — 01 §16.2.

Two things this file exists to guarantee:

1. **Migrations run as the privileged role, never the app role.** The DSN comes
   from ``MIGRATION_DATABASE_URL`` and from nowhere else. Contract §2.5: the
   application's runtime role is not the table owner and does not have
   ``BYPASSRLS``; migrations run as a separate privileged role.

2. **Two deploy pods cannot apply the same revision concurrently.** A
   transaction-scoped advisory lock serializes them.
"""

from __future__ import annotations

import asyncio
import os
from typing import Any

import packages.persistence.models  # noqa: F401 — registers every model
from alembic import context
from packages.persistence.models.base import Base
from sqlalchemy import Connection, pool, text
from sqlalchemy.ext.asyncio import async_engine_from_config

target_metadata = Base.metadata

# Two pods running `alembic upgrade head` at once would both see the same
# current revision and both try to apply the next one. The lock is transaction
# scoped, so a crashed pod releases it.
_MIGRATION_ADVISORY_LOCK = 742193847


def include_object(
    obj: Any, name: str | None, type_: str, reflected: bool, compare_to: Any
) -> bool:
    """Keep autogenerate from fighting us.

    Partitions are created by an operational job
    (``ops_create_monthly_partitions``), not by migrations, so they must not
    appear as "unexpected tables to drop". Likewise extension-owned objects.
    """
    partition_prefixes = (
        "conversations_p",
        "turns_p",
        "audit_log_p",
        "usage_events_p",
        "ai_checkpoints_p",
    )
    if type_ in ("table", "index") and name and name.startswith(partition_prefixes):
        return False
    if reflected and type_ == "table" and name in {"alembic_version"}:
        return False
    return True


def process_revision_directives(
    ctx: Any, revision: Any, directives: list[Any]
) -> None:
    """Fail loudly on an empty autogenerated migration rather than committing a
    no-op file that later confuses ``alembic history``."""
    if getattr(context.config.cmd_opts, "autogenerate", False):
        script = directives[0]
        if script.upgrade_ops.is_empty():
            directives[:] = []


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_object=include_object,
        process_revision_directives=process_revision_directives,
        compare_type=True,
        compare_server_default=True,
        # One transaction for the whole migration: a failure rolls back
        # everything. PostgreSQL has transactional DDL; we use it.
        transaction_per_migration=False,
        render_as_batch=False,
    )

    with context.begin_transaction():
        # Migrations must not be blocked forever by a long-running reader, and
        # must not themselves hold an ACCESS EXCLUSIVE lock indefinitely.
        connection.execute(text("SET lock_timeout = '5s'"))
        connection.execute(text("SET statement_timeout = '0'"))
        connection.execute(
            text("SELECT pg_advisory_xact_lock(:lock_id)"),
            {"lock_id": _MIGRATION_ADVISORY_LOCK},
        )
        context.run_migrations()


async def run_async_migrations() -> None:
    cfg = context.config.get_section(context.config.config_ini_section, {}) or {}
    # NOTE: the PRIVILEGED DSN. Never the app role's.
    try:
        cfg["sqlalchemy.url"] = os.environ["MIGRATION_DATABASE_URL"]
    except KeyError as exc:
        raise RuntimeError(
            "MIGRATION_DATABASE_URL is not set. Migrations run as the "
            "privileged role (receptionai_owner), never as receptionai_app "
            "(contract §2.5, 01 §16.1)."
        ) from exc

    engine = async_engine_from_config(cfg, prefix="sqlalchemy.", poolclass=pool.NullPool)
    async with engine.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await engine.dispose()


if context.is_offline_mode():
    raise RuntimeError(
        "Offline migrations are not supported: RLS policy DDL and role grants "
        "require a live connection."
    )

asyncio.run(run_async_migrations())
