"""Per-tenant voice configuration — the mode switch of 04 §2.1, honestly typed.

04 §2.3 lists what actually differs between the two modes. Two of those rows are
not preferences and are therefore encoded here rather than left to documentation:

* **Compliance.** In realtime mode raw caller audio goes to the model vendor and
  redaction before the model is impossible. A tenant under a BAA with one vendor
  and not another cannot switch freely, so :attr:`TenantVoiceConfig.compliance_locked_mode`
  pins the mode and :meth:`TenantVoiceConfig.resolved_mode` refuses to be
  overridden by ordinary configuration.

* **Transcript fidelity.** Composed transcripts *are* the text sent to the model.
  Realtime transcripts are a side-channel of an audio-native model and may
  disagree with what it actually responded to. Anything built on transcripts —
  QA review, analytics, compliance evidence — is less reliable in realtime, so
  the fidelity travels with the data instead of being assumed.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum

from packages.voice.turn import STOP_SECS_DEFAULT, TurnDetectionConfig

__all__ = ["TenantVoiceConfig", "TranscriptFidelity", "VoiceMode"]


class VoiceMode(StrEnum):
    """Which engine answers the call."""

    #: Separate STT, LLM and TTS wired by our own turn-taking. Exact
    #: transcripts, per-stage failover, full TTS catalogue; ~1.7-2.2s median.
    COMPOSED = "composed"

    #: One provider session takes audio in and emits audio out. ~0.5-0.9s
    #: median and native interruption, at the cost of every row in 04 §2.3.
    REALTIME = "realtime"


class TranscriptFidelity(StrEnum):
    """Whether a transcript is what the model received, or a guess at it."""

    #: The text *is* what was sent to the LLM.
    EXACT = "exact"

    #: Generated by a separate transcription pass; may differ from what the
    #: audio-native model perceived.
    APPROXIMATE = "approximate"


#: Which fidelity each mode can honestly claim. Derived, never configured — a
#: tenant cannot declare its realtime transcripts exact by setting a flag.
_FIDELITY: dict[VoiceMode, TranscriptFidelity] = {
    VoiceMode.COMPOSED: TranscriptFidelity.EXACT,
    VoiceMode.REALTIME: TranscriptFidelity.APPROXIMATE,
}


@dataclass(frozen=True, slots=True)
class TenantVoiceConfig:
    """Resolved once at session start; the shell never re-reads it mid-call."""

    mode: VoiceMode = VoiceMode.COMPOSED

    #: Set when a signed-BAA record (or its absence) fixes the mode. The admin
    #: UI cannot override this — that is the entire point of the field.
    compliance_locked_mode: VoiceMode | None = None

    stt_provider: str = "deepgram"
    tts_provider: str = "deepgram"
    llm_provider: str | None = None
    realtime_provider: str = "openai"

    #: Deepgram model ids. Defaults are the pair verified working against this
    #: account: nova-3 for STT, aura-2 for TTS.
    stt_model: str = "nova-3"
    stt_language: str = "en"
    tts_voice: str = "aura-2-thalia-en"

    #: End-of-turn silence, seconds. Clamped by
    #: :func:`packages.voice.turn.clamp_stop_secs` at the point of use.
    stop_secs: float = STOP_SECS_DEFAULT

    #: Which end-of-turn detector runs and whether speculation is on. The
    #: default is the silence baseline above, unchanged.
    turn_detection: TurnDetectionConfig = field(default_factory=TurnDetectionConfig)

    #: Spoken at the start of the call by the shell, not by the model.
    greeting: str | None = None

    #: Phrases boosted in STT. Months and booking vocabulary transcribe badly
    #: without this, and a misheard month books the wrong appointment.
    keyterms: tuple[str, ...] = field(default_factory=tuple)

    @property
    def resolved_mode(self) -> VoiceMode:
        """The mode that will actually run, compliance winning over preference."""
        return self.compliance_locked_mode or self.mode

    @property
    def transcript_fidelity(self) -> TranscriptFidelity:
        """How much downstream consumers may trust this call's transcript."""
        return _FIDELITY[self.resolved_mode]
